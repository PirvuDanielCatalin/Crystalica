/**
 * Cloudflare Pages + @astrojs/cloudflare (Workers target) bridge.
 *
 * The adapter emits an SSR worker in `dist/server/` (entry.mjs + chunks), but the
 * Pages project is configured to publish `dist/client/` only. Without a worker the
 * only on-demand route (`/@[username]`, prerender = false) falls back to the static
 * 404 page.
 *
 * Pages runs a worker located at `<output>/_worker.js/` (advanced mode) for every
 * request, so copying the server bundle there makes SSR routes work again while
 * keeping the same URL and the existing GitHub -> Pages continuous deployment.
 */
import { cp, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const serverDir = path.join(root, 'dist/server');
const workerDir = path.join(root, 'dist/client/_worker.js');

try {
  await rm(workerDir, { recursive: true, force: true });
  await cp(serverDir, workerDir, { recursive: true });

  // The adapter's own wrangler config is meaningless inside the Pages bundle and
  // makes wrangler refuse to start when a generated deploy config is present.
  await rm(path.join(workerDir, 'wrangler.json'), { force: true });

  // Pages expects the entry point to be named index.js; re-export the Astro handler.
  await writeFile(
    path.join(workerDir, 'index.js'),
    "export * from './entry.mjs';\nexport { default } from './entry.mjs';\n",
    'utf8',
  );

  // Generated by the adapter for `wrangler dev/deploy`. Wrangler refuses to run in
  // Pages mode while it exists, so drop it; `astro build` regenerates it on demand.
  await rm(path.join(root, '.wrangler/deploy'), { recursive: true, force: true });

  console.log('[build] Cloudflare Pages worker prepared at dist/client/_worker.js');
} catch (error) {
  console.error('[build] Failed to prepare the Cloudflare Pages worker:', error);
  process.exit(1);
}
